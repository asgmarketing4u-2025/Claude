#!/usr/bin/env python3
"""
Generate queries.txt (category | City, ST) for the no-website finder.

Edit CATEGORIES and CITIES below and run:  python gen_queries.py
It writes queries.txt as the cross-product category x city, grouped by region.

Each line becomes one Google Places text search ("<category> in <City, ST>")
returning up to ~60 businesses, so total API lookups scale with
len(CATEGORIES) * len(all cities). Trim either list to control cost, and use
places_finder.py --limit N to run a slice at a time.
"""

from __future__ import annotations

# Service / trade businesses that most often have NO website — best agency prospects.
CATEGORIES = [
    "plumber",
    "electrician",
    "hvac contractor",
    "roofing contractor",
    "landscaping",
    "lawn care",
    "auto repair",
    "barber shop",
    "nail salon",
    "hair salon",
    "house cleaning service",
    "pest control",
    "handyman",
    "towing service",
]

# Cities grouped by region. Add/remove freely.
CITIES: dict[str, list[str]] = {
    "Maryland / Baltimore": [
        "Baltimore, MD", "Dundalk, MD", "Towson, MD", "Essex, MD", "Catonsville, MD",
        "Glen Burnie, MD", "Columbia, MD", "Ellicott City, MD", "Annapolis, MD",
        "Bowie, MD", "Silver Spring, MD", "Rockville, MD", "Gaithersburg, MD",
        "Frederick, MD", "Hagerstown, MD", "Salisbury, MD",
    ],
    "Washington, DC": [
        "Washington, DC",
    ],
    "Virginia": [
        "Richmond, VA", "Virginia Beach, VA", "Norfolk, VA", "Chesapeake, VA",
        "Newport News, VA", "Hampton, VA", "Alexandria, VA", "Arlington, VA",
        "Roanoke, VA", "Lynchburg, VA", "Fredericksburg, VA", "Charlottesville, VA",
        "Manassas, VA", "Portsmouth, VA",
    ],
    "New Jersey": [
        "Newark, NJ", "Jersey City, NJ", "Paterson, NJ", "Elizabeth, NJ",
        "Trenton, NJ", "Edison, NJ", "Camden, NJ", "Clifton, NJ", "Toms River, NJ",
        "Atlantic City, NJ", "New Brunswick, NJ", "Cherry Hill, NJ", "Vineland, NJ",
        "Woodbridge, NJ",
    ],
    "North Carolina": [
        "Charlotte, NC", "Raleigh, NC", "Greensboro, NC", "Durham, NC",
        "Winston-Salem, NC", "Fayetteville, NC", "Cary, NC", "Wilmington, NC",
        "High Point, NC", "Greenville, NC", "Asheville, NC", "Concord, NC",
        "Gastonia, NC", "Jacksonville, NC",
    ],
}

HEADER = """# Google Places queries for the no-website finder.
# Format:  category | City, ST   (one Places search each, ~60 results max)
# GENERATED by gen_queries.py — edit that script's CATEGORIES/CITIES and re-run.
#
# Cost scales with the number of lines below. Start with a slice:
#   python places_finder.py --queries queries.txt --out no_website_leads.csv --limit 20
# It resumes, so run more slices (or drop --limit) as you go.
"""


def main() -> None:
    total_cities = sum(len(v) for v in CITIES.values())
    lines = [HEADER]
    lines.append(f"# {len(CATEGORIES)} categories x {total_cities} cities = "
                 f"{len(CATEGORIES) * total_cities} queries\n")
    count = 0
    for region, cities in CITIES.items():
        lines.append(f"# ================= {region} =================")
        for city in cities:
            for cat in CATEGORIES:
                lines.append(f"{cat} | {city}")
                count += 1
        lines.append("")
    with open("queries.txt", "w", encoding="utf-8") as f:
        f.write("\n".join(lines).rstrip() + "\n")
    print(f"Wrote queries.txt: {count} queries "
          f"({len(CATEGORIES)} categories x {total_cities} cities).")


if __name__ == "__main__":
    main()
